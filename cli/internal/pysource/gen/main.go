//go:build ignore

// gen writes source_gen.go in the parent (pysource) package.
// It embeds the Python runtime source tree (pyproject.toml + src/) as a
// testing/fstest.MapFS so it can be included in the Go binary without relying
// on PyPI. Run via:
//
//	go generate contained.dev/cli/internal/pysource
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	// Generator runs from the pysource package directory (cli/internal/pysource/).
	// The workspace root is three directories up.
	root := filepath.Join("..", "..", "..")

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen/main.go; DO NOT EDIT.\n")
	buf.WriteString("// Regenerate with: go generate contained.dev/cli/internal/pysource\n\n")
	buf.WriteString("package pysource\n\n")
	buf.WriteString("import \"testing/fstest\"\n\n")
	buf.WriteString("var sourceFS = fstest.MapFS{\n")

	// Walk entries: pyproject.toml then src/
	entries := collectFiles(root)
	for _, e := range entries {
		content, err := os.ReadFile(filepath.Join(root, e))
		if err != nil {
			fmt.Fprintf(os.Stderr, "read %s: %v\n", e, err)
			os.Exit(1)
		}
		fmt.Fprintf(&buf, "\t%q: {Data: %s},\n", e, byteSliceLiteral(content))
	}

	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		// Write unformatted so the error is visible
		os.WriteFile("source_gen.go", buf.Bytes(), 0o644)
		fmt.Fprintf(os.Stderr, "gofmt: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile("source_gen.go", src, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write source_gen.go: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("wrote source_gen.go")
}

// collectFiles returns relative paths (using forward slashes) for all files
// under root/src and root/pyproject.toml, skipping __pycache__ and .DS_Store.
func collectFiles(root string) []string {
	var out []string
	out = append(out, "pyproject.toml")
	filepath.WalkDir(filepath.Join(root, "src"), func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "__pycache__" {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Name() == ".DS_Store" {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		out = append(out, filepath.ToSlash(rel))
		return nil
	})
	return out
}

// byteSliceLiteral returns a Go expression for the byte slice. For valid UTF-8
// text (typical for Python source) it uses a raw string literal for readability.
func byteSliceLiteral(b []byte) string {
	if isValidUTF8Text(b) {
		s := string(b)
		// Use raw string literal if the content has no backtick.
		if !strings.Contains(s, "`") {
			return "[]byte(`" + s + "`)"
		}
		// Fall through to quoted string for content with backticks.
	}
	// Fallback: hex byte slice literal for binary content or backtick-containing text.
	var sb strings.Builder
	sb.WriteString("[]byte{")
	for i, c := range b {
		if i > 0 {
			sb.WriteString(", ")
		}
		fmt.Fprintf(&sb, "0x%02x", c)
	}
	sb.WriteString("}")
	return sb.String()
}

func isValidUTF8Text(b []byte) bool {
	for _, r := range string(b) {
		if r == 0xFFFD {
			return false
		}
	}
	return true
}
